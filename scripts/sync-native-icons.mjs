function assPath(svg, size){
 return svg.split(/(?=M)/).filter(s=>s.trim()).map(part=>strokePath(part,size)).join(" ")
}
function strokePath(svg, size){
 const tokens=svg.match(/[a-zA-Z]|[-+]?(?:\d*\.\d+|\d+)(?:[eE][-+]?\d+)?/g);let i=0,command='',x=0,y=0,startX=0,startY=0,points=[]
 const n=()=>Number(tokens[i++])*size/24
 while(i<tokens.length){
  if(/[a-zA-Z]/.test(tokens[i]))command=tokens[i++]
  if(command==='M'){x=n();y=n();startX=x;startY=y;points.push([x,y]);command='L'}
  else if(command==='L'){x=n();y=n();points.push([x,y])}
  else if(command==='C'){const ax=x,ay=y,a=n(),b=n(),c=n(),d=n();x=n();y=n();for(let j=1;j<=12;j++){const t=j/12,u=1-t;points.push([u*u*u*ax+3*u*u*t*a+3*u*t*t*c+t*t*t*x,u*u*u*ay+3*u*u*t*b+3*u*t*t*d+t*t*t*y])}}
  else if(command==='V'){y=n();points.push([x,y])}
  else if(command==='H'){x=n();points.push([x,y])}
  else if(command==='Z'){points.push([startX,startY]);command=''}
  else throw Error('Unsupported SVG path command: '+command)
 }
 points=points.filter((p,i)=>i===0||Math.hypot(p[0]-points[i-1][0],p[1]-points[i-1][1])>.001)
 const half=size/24*.8,left=[],right=[]
 for(let j=0;j<points.length;j++){
  const prev=points[Math.max(0,j-1)],next=points[Math.min(points.length-1,j+1)]
  const dx=next[0]-prev[0],dy=next[1]-prev[1],length=Math.hypot(dx,dy)||1
  left.push([points[j][0]-dy/length*half,points[j][1]+dx/length*half]);right.push([points[j][0]+dy/length*half,points[j][1]-dx/length*half])
 }
 return [...left,...right.reverse(),left[0]].map((p,j)=>(j?'l ':'m ')+p.map(n=>Math.round(n*100)/100).join(' ')).join(' ')
}
